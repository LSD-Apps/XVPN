/// 出站标签的**单一来源**。
///
/// 为什么单独抽一个文件：这两个字符串散落在配置生成、Clash API 解析、流量统计、
/// 路由规则生成与自动纠正表里，共 5 处以上。此前它们是各自写死的字面量——
/// 风险不对称且很隐蔽：若哪天改了标签，**路由仍然照常工作**，但所有按出站判定
/// 「这条连接走了隧道吗」的地方会全部失效，表现为隧道在工作而界面上「走隧道 0 B」。
/// 那正是本项目反复记录过的那类「界面承诺了但没做到」的故障，而且不会报错。
///
/// 放在独立模块而不是挂在 `SingBoxConfigBuilder` 上：`clash_api.dart` 是底层
/// 的响应解析器，不该为了两个常量去依赖配置生成器。
library;

/// 内核配置里两个出站/端点的标签。
///
/// * [vpn] 指向隧道（`endpoints[]` 或 `outbounds[]` 里那个代理出站）；
/// * [direct] 指向直连出站。
class OutboundTags {
  OutboundTags._();

  /// 隧道出站标签。也是 `route.final` 在智能分流下的取值。
  static const String vpn = 'vpn';

  /// 直连出站标签。
  static const String direct = 'direct';
}
